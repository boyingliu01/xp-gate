import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';

import {
  backupThenRemove, hasXpGateMarker, scanSkillResidue, pruneDeadRoots,
  contentHashes, MARKER_SCAN_LIMIT, sweepLegacySelfCopy,
} from '../scripts/lib/residue.mjs';
import { hashTree, isFile } from '../scripts/lib/util.mjs';
import { tmpDir, fakePkg, deploySkill, editSkill } from './fixtures.mjs';

/** Stand-in for a user-edited SKILL.md; must differ from the bundled one. */
const USER_EDIT = '# edited by the user\n';

// --- backupThenRemove: every call in reinstall deletes user data ------------

test('backupThenRemove copies a directory into residue/ then deletes the original', (t) => {
  const runDir = tmpDir(t);
  const victim = tmpDir(t);
  fs.writeFileSync(path.join(victim, 'a.txt'), 'important');
  fs.mkdirSync(path.join(victim, 'nested'));
  fs.writeFileSync(path.join(victim, 'nested', 'b.txt'), 'deep');

  backupThenRemove(victim, runDir, path.join('skills', 'DSH-thing'));

  assert.equal(fs.existsSync(victim), false, 'original must be gone');
  const backup = path.join(runDir, 'residue', 'skills', 'DSH-thing');
  assert.equal(fs.readFileSync(path.join(backup, 'a.txt'), 'utf8'), 'important');
  assert.equal(fs.readFileSync(path.join(backup, 'nested', 'b.txt'), 'utf8'), 'deep');
});

test('backupThenRemove handles a single file entry', (t) => {
  const runDir = tmpDir(t);
  const victim = tmpDir(t);
  const file = path.join(victim, 'pre-commit');
  fs.writeFileSync(file, '#!/bin/sh\n# xp-gate');

  backupThenRemove(file, runDir, path.join('project-hooks', 'pre-commit'), true);

  assert.equal(fs.existsSync(file), false);
  assert.equal(
    fs.readFileSync(path.join(runDir, 'residue', 'project-hooks', 'pre-commit'), 'utf8'),
    '#!/bin/sh\n# xp-gate'
  );
});

test('backupThenRemove creates nested label directories', (t) => {
  const runDir = tmpDir(t);
  const victim = tmpDir(t);
  fs.writeFileSync(path.join(victim, 'f'), 'x');

  // Labels like "templates/<agent>/git-hooks-template" are three levels deep.
  assert.doesNotThrow(() => backupThenRemove(victim, runDir, 'templates/Qoder/git-hooks-template'));
  assert.ok(isFile(path.join(runDir, 'residue', 'templates', 'Qoder', 'git-hooks-template', 'f')));
});

// --- hasXpGateMarker: guards against deleting unrelated directories --------

test('hasXpGateMarker finds the marker in a nested file', (t) => {
  const dir = tmpDir(t);
  fs.mkdirSync(path.join(dir, 'hooks'));
  fs.writeFileSync(path.join(dir, 'hooks', 'pre-commit'), '#!/bin/sh\n# generated by xp-gate\n');

  assert.equal(hasXpGateMarker(dir), true);
});

test('hasXpGateMarker matches case-insensitively', (t) => {
  const dir = tmpDir(t);
  fs.writeFileSync(path.join(dir, 'f'), 'XP-GATE');

  assert.equal(hasXpGateMarker(dir), true);
});

test('hasXpGateMarker returns false for an unrelated directory', (t) => {
  const dir = tmpDir(t);
  fs.writeFileSync(path.join(dir, 'mine.sh'), 'echo hello\n');

  // This is the whole safety property: no marker means do NOT delete.
  assert.equal(hasXpGateMarker(dir), false);
});

test('hasXpGateMarker returns false for an empty or missing directory', (t) => {
  const dir = tmpDir(t);
  assert.equal(hasXpGateMarker(dir), false);
  assert.equal(hasXpGateMarker('/no/such/dir'), false);
});

test('hasXpGateMarker tolerates binary files without throwing', (t) => {
  const dir = tmpDir(t);
  fs.writeFileSync(path.join(dir, 'binary.bin'), Buffer.from([0x00, 0xff, 0xfe]));
  fs.writeFileSync(path.join(dir, 'note.md'), 'xp-gate');

  assert.equal(hasXpGateMarker(dir), true);
});

test('hasXpGateMarker caps how many files it inspects', (t) => {
  const dir = tmpDir(t);
  // Marker sits beyond the cap; the bounded scan must return false rather than
  // walking an unbounded tree.
  for (let i = 0; i < MARKER_SCAN_LIMIT + 5; i += 1) {
    fs.writeFileSync(path.join(dir, `f${String(i).padStart(3, '0')}.txt`), 'plain');
  }
  fs.writeFileSync(path.join(dir, 'zzz-last.txt'), 'xp-gate');

  assert.equal(hasXpGateMarker(dir), false);
});

// --- scanSkillResidue: decides what is safe to delete ----------------------

test('scanSkillResidue separates byte-identical copies from user-modified ones', (t) => {
  const pkg = fakePkg(t, ['alpha']);
  const root = tmpDir(t);
  const srcHash = hashTree(path.join(pkg, 'skills', 'alpha'));

  deploySkill(pkg, root, 'alpha');
  editSkill(deploySkill(pkg, root, 'alpha', 'beta'), '# edited\n');

  const oldHashes = new Map([['alpha', srcHash], ['beta', srcHash]]);
  const { identical, modified } = scanSkillResidue([{ agent: 'A', dir: root }], oldHashes);

  assert.deepEqual(identical.map((r) => r.name), ['alpha']);
  assert.deepEqual(modified.map((r) => r.name), ['beta']);
});

test('scanSkillResidue ignores directories that are not in the old package', (t) => {
  const root = tmpDir(t);
  fs.mkdirSync(path.join(root, 'unrelated'));
  fs.writeFileSync(path.join(root, 'unrelated', 'x'), 'y');

  const { identical, modified } = scanSkillResidue([{ agent: 'A', dir: root }], new Map());
  assert.deepEqual(identical, []);
  assert.deepEqual(modified, []);
});

test('scanSkillResidue skips unreadable roots', () => {
  const result = scanSkillResidue([{ agent: 'A', dir: '/no/such/root' }], new Map([['alpha', 'deadbeef']]));
  assert.deepEqual(result, { identical: [], modified: [] });
});

// --- pruneDeadRoots: deletes only exact matches ----------------------------

test('pruneDeadRoots deletes byte-identical copies but spares edited ones', (t) => {
  // Two dead agent roots each holding the SAME skill name: one untouched, one
  // edited by the user. This is the exact case the hash comparison exists for.
  // Naming the edited copy something else would make this pass for the wrong
  // reason -- contentHashes() only iterates names present in the package, so a
  // differently-named dir is skipped before any hash is ever computed.
  const pkg = fakePkg(t, ['alpha']);
  const untouched = tmpDir(t);
  const edited = tmpDir(t);

  deploySkill(pkg, untouched, 'alpha');
  editSkill(deploySkill(pkg, edited, 'alpha'), USER_EDIT);

  const removed = pruneDeadRoots(pkg, [
    { agent: 'Untouched', dir: untouched },
    { agent: 'Edited', dir: edited },
  ]);

  assert.equal(removed, 1);
  assert.equal(fs.existsSync(path.join(untouched, 'alpha')), false, 'identical copy must go');
  // Dropping the hash check deletes this too -- silent data loss.
  assert.equal(fs.existsSync(path.join(edited, 'alpha')), true, 'edited copy is user data');
  assert.equal(fs.readFileSync(path.join(edited, 'alpha', 'SKILL.md'), 'utf8'), USER_EDIT);
});

/** What install.mjs actually writes: the whole tree, front matter included. */
const SELF_SKILL_MD = ['---', 'name: xp-gate-reinstall', 'version: 1.3.3', '---', '', '# self', ''].join('\n');

/** An agent root holding a pre-2.0.0 self copy. */
function legacySelfRoot(t, contents = SELF_SKILL_MD) {
  const root = tmpDir(t);
  const legacy = path.join(root, 'xp-gate-reinstall');
  fs.mkdirSync(legacy);
  fs.writeFileSync(path.join(legacy, 'SKILL.md'), contents);
  return { root, legacy };
}

test('pruneDeadRoots also removes a stray copy under the OLD skill name', (t) => {
  // The skill was renamed xp-gate-reinstall -> reinstall-xp-gate in 2.0.0. Every
  // machine that ran the old installer has a copy under the old name in each
  // agent root. Nothing would ever update that copy again -- the package ships
  // nothing under that name any more -- so it has to be swept automatically, or
  // a fleet of stale skills accumulates.
  const pkg = fakePkg(t, ['alpha']);
  const { root, legacy } = legacySelfRoot(t);

  assert.equal(pruneDeadRoots(pkg, [{ agent: 'A', dir: root }]), 1);
  assert.equal(fs.existsSync(legacy), false, 'legacy copy must be swept');
});

test('pruneDeadRoots leaves an EDITED legacy copy alone', (t) => {
  // Same rule as every other skill here: an exact copy of ours is ours to
  // delete, an edited one is user data. The rename must not become a licence to
  // delete whatever happens to sit under the old name.
  const pkg = fakePkg(t, ['alpha']);
  const { root, legacy } = legacySelfRoot(t, `${USER_EDIT}\n`);

  pruneDeadRoots(pkg, [{ agent: 'A', dir: root }]);

  assert.equal(fs.existsSync(legacy), true, 'an edited legacy copy is user data');
});

test('a copy is only ours when its name: line matches exactly', (t) => {
  // The marker decides whether a directory may be deleted. A substring or
  // prefix match would let `name: reinstall-xp-gate-fork` be swept as ours, so
  // the comparison is exact on both names.
  const { root } = legacySelfRoot(t, ['---', 'name: reinstall-xp-gate-fork', '---', ''].join('\n'));

  assert.equal(sweepLegacySelfCopy(root), 0, 'a fork is not ours');
  assert.equal(fs.existsSync(path.join(root, 'xp-gate-reinstall')), true);
});

test('pruneDeadRoots does nothing when the package has no skills', (t) => {
  const root = tmpDir(t);
  const pkg = tmpDir(t, 'xgr-empty-pkg-');

  assert.equal(pruneDeadRoots(pkg, [{ agent: 'A', dir: root }]), 0);
});

test('pruneDeadRoots never touches unrelated directories', (t) => {
  const pkg = fakePkg(t, ['alpha']);
  const root = tmpDir(t);
  fs.mkdirSync(path.join(root, 'my-own-skill'));
  fs.writeFileSync(path.join(root, 'my-own-skill', 'SKILL.md'), '# mine\n');

  pruneDeadRoots(pkg, [{ agent: 'A', dir: root }]);

  assert.equal(fs.existsSync(path.join(root, 'my-own-skill')), true);
});

// --- contentHashes --------------------------------------------------------

test('contentHashes maps skill names to directory hashes', (t) => {
  const pkg = fakePkg(t, ['alpha', 'beta']);
  const hashes = contentHashes(pkg);

  assert.deepEqual([...hashes.keys()].sort(), ['alpha', 'beta']);
  assert.match(hashes.get('alpha'), /^[a-f0-9]{64}$/);
});

test('contentHashes returns an empty map for a package without skills/', (t) => {
  assert.equal(contentHashes(tmpDir(t)).size, 0);
  assert.equal(contentHashes('/no/such/pkg').size, 0);
});

test('sweepLegacySelfCopy clears the old name in a LIVE agent root too', (t) => {
  // pruneDeadRoots only ever sees agents judged dead. The rename has to reach
  // every root that is still in use as well -- measured during the real 2.0.0
  // install: six new copies were written and all five old ones stayed behind,
  // because nothing in install.mjs looked at the legacy name at all.
  const { root, legacy } = legacySelfRoot(t);

  const removed = sweepLegacySelfCopy(root);

  assert.equal(removed, 1);
  assert.equal(fs.existsSync(legacy), false);
});

test('sweepLegacySelfCopy leaves an edited legacy copy alone', (t) => {
  const { root, legacy } = legacySelfRoot(t, `${USER_EDIT}\n`);

  assert.equal(sweepLegacySelfCopy(root), 0);
  assert.equal(fs.existsSync(legacy), true);
});

test('sweepLegacySelfCopy never touches the current name', (t) => {
  // The sweep runs from install.mjs right after the current copy is written;
  // deleting that would undo the install it is part of.
  const root = tmpDir(t);
  const current = path.join(root, 'reinstall-xp-gate');
  fs.mkdirSync(current);
  fs.writeFileSync(path.join(current, 'SKILL.md'), SELF_SKILL_MD.replace('xp-gate-reinstall', 'reinstall-xp-gate'));

  assert.equal(sweepLegacySelfCopy(root), 0);
  assert.equal(fs.existsSync(current), true);
});
