/**
 * arch-config-template.js — 项目级默认架构配置的单一来源（REQ-DEPLOY-003）
 *
 * WHY THIS FILE EXISTS
 * --------------------
 * Gate 6 自 2026-05-04 起对「没有架构配置文件」的项目直接阻塞提交
 * （`githooks/pre-commit:4838` 逐字输出 `❌ ARCHITECTURE CONFIG MISSING - COMMIT BLOCKED`）。
 * 实测该判定是纯文件存在性检查：
 *
 *     [ -f "$PROJECT_ROOT/architecture.yaml" ] || [ -f "$PROJECT_ROOT/.architecturerc" ] \
 *       || [ -f "$PROJECT_ROOT/.archlint.yaml" ]
 *
 * 它**从不解析内容**。于是 `xp-gate init` 装好了全部 gate，用户第一次 commit 却被
 * 拦住，原因与代码质量无关——只是因为少一个文件。这就是本模块要消除的失败模式：
 * 安装成功的产品在新项目里不可用。
 *
 * WHY THE CONTENT CONTAINS ZERO CONFIGURATION KEYS
 * -----------------------------------------------
 * 实测（设计文档 §3.4 实验 D/E）：
 *   - 在 archlint 0.16.0 下写 `ignore: ["src/b.ts"]`，`files_analyzed` 仍是 2、
 *     `cyclic_dependencies` 仍是 1 —— **该键被静默忽略**。
 *   - 只含注释的配置文件与"没有配置文件"行为完全一致。
 *
 * 所以生成一份写了规则的配置，会让用户看到「已配置架构约束」而实际什么都没约束。
 * 那比没有文件更糟：没有文件至少是诚实的。本模板因此**只写注释**，它的价值全部
 * 来自三件事：
 *   1. 让 Gate 6 的存在性前置条件成立（这是它的唯一功能作用）；
 *   2. 承载说明：为什么是空的、怎么验证、想要真配置时该看什么；
 *   3. 给用户一个将来可以往里加东西的地方。
 *
 * GLOBAL INSTALL MUST NOT WRITE THIS
 * ----------------------------------
 * 用户决策（sprint-20261110-33）：默认架构配置只在**项目级** init 生成。
 * 全局安装写用户 HOME 会让一份项目相关的文件变成机器级副作用。
 * 本模块因此不引用 HOME / homedir，写入由 init.js 的 installLocal 路径负责。
 */
'use strict';

/** 生成的文件名。与 pre-commit 的三个存在性判定之一逐字对应。 */
const CONFIG_FILENAME = '.archlint.yaml';

/**
 * 生成内容。只有一个作用：让 Gate 6 的存在性检查通过，并把这件事说清楚。
 *
 * 新增这里的文案时注意：它是**新增文案契约**（约束我们自己产出什么），
 * 不是对既有输出的观测。测试从本常量读取，不重写字面量——两处各写一份
 * 迟早会漂移，而漂移后测试仍然为真。
 */
const ARCH_CONFIG_TEMPLATE = `# Architecture lint configuration for Gate 6.
#
# This file deliberately contains no configuration keys.
#
# WHY IT IS EMPTY
#   Gate 6 blocks a commit when no architecture config file exists — it checks
#   for the file's existence only and never parses what is inside:
#
#       [ -f architecture.yaml ] || [ -f .architecturerc ] || [ -f .archlint.yaml ]
#
#   So this file's job is to satisfy that precondition, nothing more. It is
#   generated by 'xp-gate init' so a freshly set-up project can commit.
#
# WHY THERE ARE NO RULES HERE
#   Writing rules that the tool silently ignores would be worse than an empty
#   file: the file would look configured while constraining nothing. Verified
#   against archlint 0.16.0 that keys such as 'ignore:' and 'rules:' have no
#   effect on the analysis, so none are written.
#
# WHAT ACTUALLY RUNS
#   With no keys set, archlint's own default detectors apply. To see exactly
#   which detectors are active:
#
#       archlint detectors list
#
# HOW TO CONFIGURE FOR REAL
#   Add keys below once you have confirmed they take effect for your installed
#   archlint version. Check the difference in the report before and after:
#
#       archlint -f json . | head -40
#
#   Delete this file and Gate 6 will block commits again until another config
#   file (architecture.yaml or .architecturerc) is present.
`;

module.exports = Object.freeze({
  CONFIG_FILENAME,
  ARCH_CONFIG_TEMPLATE,
});
