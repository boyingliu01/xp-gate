/**
 * @test REQ-767
 * @intent `xp-gate init` 往项目里写 githooks 适配器副本、.xp-gate/ 模块镜像和生成的
 *         .xp-gate-config.json，却从不写 .gitignore：这些机器相关的产物全部以未跟踪
 *         条目出现在 git status 里，file-hygiene/debt 门禁把生成物当成未提交源码，
 *         造成用户无法自行修复的 Gate 6 零容忍 BLOCK(#767)
 * @covers AC-767-01, AC-767-02, AC-767-03, AC-767-04
 */
const fs = require('fs');
const path = require('path');
const os = require('os');

const { ensureGitignoreEntries, gitignoreEntriesForInit } = require('../init');

function makeProject(gitignoreContent) {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'xpgate-gitignore-'));
  if (gitignoreContent !== undefined) {
    fs.writeFileSync(path.join(root, '.gitignore'), gitignoreContent);
  }
  return root;
}

describe('init .gitignore management (#767)', () => {
  let root;

  afterEach(() => {
    if (root) fs.rmSync(root, { recursive: true, force: true });
    root = null;
  });

  it('creates .gitignore when the project has none', () => {
    root = makeProject(undefined);
    const added = ensureGitignoreEntries(root);

    expect(added.length).toBeGreaterThan(0);
    expect(fs.readFileSync(path.join(root, '.gitignore'), 'utf8')).toContain('.xp-gate-config.json');
  });

  it('keeps the user\'s existing rules untouched', () => {
    root = makeProject('node_modules/\ndist/\n');
    ensureGitignoreEntries(root);

    const content = fs.readFileSync(path.join(root, '.gitignore'), 'utf8');
    expect(content.startsWith('node_modules/\ndist/\n')).toBe(true);
  });

  // Re-running init is a documented repair action; a second appended block would
  // grow the file on every run and make the diff look like a real change.
  it('is idempotent — a second run adds nothing', () => {
    root = makeProject('node_modules/\n');
    const first = ensureGitignoreEntries(root);
    const second = ensureGitignoreEntries(root);

    expect(first.length).toBeGreaterThan(0);
    expect(second).toEqual([]);
  });

  // The empty-return above is not sufficient proof of idempotency: the first
  // version excluded comment lines from the presence set, so every run appended
  // another copy of the section headers while still returning []. Assert on the
  // FILE so a header-only regression cannot hide behind an empty return value.
  it('is idempotent at the file level — repeated runs leave the file byte-identical', () => {
    root = makeProject('node_modules/\n');
    ensureGitignoreEntries(root);
    const afterFirst = fs.readFileSync(path.join(root, '.gitignore'), 'utf8');
    ensureGitignoreEntries(root);
    ensureGitignoreEntries(root);

    expect(fs.readFileSync(path.join(root, '.gitignore'), 'utf8')).toBe(afterFirst);
    const header = '# xp-gate: generated by `xp-gate init`';
    expect(afterFirst.split(header).length - 1).toBe(1);
  });

  it('adds only the rules that are missing', () => {
    root = makeProject('.xp-gate-config.json\n');
    const added = ensureGitignoreEntries(root);

    expect(added).not.toContain('.xp-gate-config.json');
    expect(added).toContain('.xp-gate/lint-baseline.json');
  });

  it('does not append a rule already present with surrounding whitespace', () => {
    root = makeProject('  .xp-gate-config.json  \n');
    expect(ensureGitignoreEntries(root)).not.toContain('.xp-gate-config.json');
  });

  // The regression guard that matters most: the hook entrypoints and the gate
  // registry are real project source. Ignoring them would un-version exactly the
  // files a user needs to customise and the file that binds gate names to scripts.
  it('never ignores the committable githooks entrypoints or the registry', () => {
    const patterns = gitignoreEntriesForInit();
    for (const mustStayTracked of [
      'githooks/pre-commit',
      'githooks/pre-push',
      'githooks/adapter-common.sh',
      'githooks/gate-registry.sh',
      'githooks/gate-3.sh',
    ]) {
      expect(patterns).not.toContain(mustStayTracked);
    }
    // No broad `githooks/` rule either — that would swallow the entrypoints.
    expect(patterns).not.toContain('githooks/');
  });

  it('ignores the per-language adapter copies that init installs', () => {
    const patterns = gitignoreEntriesForInit();
    expect(patterns).toContain('githooks/csharp.sh');
    expect(patterns).toContain('githooks/adapters/gate-*.sh');
  });

  // Appending must not corrupt a file whose last line lacks a newline.
  it('separates the block from a file with no trailing newline', () => {
    root = makeProject('node_modules/');
    ensureGitignoreEntries(root);

    const content = fs.readFileSync(path.join(root, '.gitignore'), 'utf8');
    expect(content).toContain('node_modules/\n');
    expect(content.split('\n')).toContain('.xp-gate-config.json');
  });
});

/**
 * @test REQ-767
 * @intent Delphi round 2 (FC-05): merging the block used a bare writeFileSync, which
 *         truncates before writing. An ENOSPC or a killed process mid-write would
 *         leave the user's .gitignore truncated — destroying the rules this feature
 *         promises to preserve, in a file xp-gate does not own. A temp file plus
 *         rename is atomic within a directory: the file is either the old content or
 *         the complete new content.
 * @covers AC-767-05
 */
describe('init .gitignore write is atomic (#767)', () => {
  let root;

  afterEach(() => {
    if (root) fs.rmSync(root, { recursive: true, force: true });
    root = null;
  });

  it('never leaves a truncated .gitignore when the write fails', () => {
    root = makeProject('node_modules/\ndist/\n');
    const original = fs.readFileSync(path.join(root, '.gitignore'), 'utf8');
    const writeSpy = vi.spyOn(fs, 'writeFileSync').mockImplementation(() => {
      throw Object.assign(new Error('ENOSPC: no space left on device'), { code: 'ENOSPC' });
    });

    expect(() => ensureGitignoreEntries(root)).toThrow(/ENOSPC/);
    writeSpy.mockRestore();

    // The user's rules survive untouched: the failed write went to the temp file.
    expect(fs.readFileSync(path.join(root, '.gitignore'), 'utf8')).toBe(original);
  });

  it('leaves no temp file behind after a successful write', () => {
    root = makeProject('node_modules/\n');
    ensureGitignoreEntries(root);

    expect(fs.existsSync(path.join(root, '.gitignore.xp-gate-tmp'))).toBe(false);
  });

  // Delphi round 1 (CI-02): init resolved the gitignore root from process.cwd() while
  // installLocal resolved it from the .git directory. Running from a subdirectory
  // therefore wrote .gitignore next to the caller while the adapters landed at the
  // repo root — the rules guarded a tree with no generated files. This pins the
  // contract the fix relies on: the helper obeys the root it is given.
  it('writes to the root it is given, not to the current working directory', () => {
    root = makeProject('node_modules/\n');
    const subdir = path.join(root, 'packages', 'app');
    fs.mkdirSync(subdir, { recursive: true });
    const cwdSpy = vi.spyOn(process, 'cwd').mockReturnValue(subdir);

    ensureGitignoreEntries(root);

    expect(fs.existsSync(path.join(root, '.gitignore'))).toBe(true);
    expect(fs.existsSync(path.join(subdir, '.gitignore'))).toBe(false);
    cwdSpy.mockRestore();
  });

  // Delphi round 1 (CI-03): the original wiring swallowed every error, so a read-only
  // checkout left the user in the exact #767 state while init still reported success.
  // The helper must surface the failure rather than absorb it.
  it('propagates a write failure instead of reporting success', () => {
    root = makeProject('node_modules/\n');
    const writeSpy = vi.spyOn(fs, 'writeFileSync').mockImplementation(() => {
      throw new Error('EACCES: permission denied');
    });

    expect(() => ensureGitignoreEntries(root)).toThrow(/EACCES/);
    writeSpy.mockRestore();
  });

  // The returned list is what init reports as "N entries added", so it must count
  // RULES. Section headers are written to the file but would inflate that number and
  // read to the user as ignored files that are not ignore rules.
  it('reports rules only — section comments are written but never counted', () => {
    root = makeProject('node_modules/\n');
    const added = ensureGitignoreEntries(root);

    expect(added.length).toBeGreaterThan(0);
    expect(added.filter((line) => line.startsWith('#'))).toEqual([]);
    const written = fs.readFileSync(path.join(root, '.gitignore'), 'utf8');
    expect(written).toContain('# xp-gate: generated by');
  });
});
